import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const root = process.cwd();
const matrixPath = path.join(
  root,
  'docs/backend-implementation/steps/00-execution-contract/ROUTE-PARITY-MATRIX.md',
);
const outputPath = path.join(
  root,
  'docs/backend-implementation/steps/22-postman-backend-freeze/ENDPOINT-COVERAGE-MATRIX.md',
);
const openapi = JSON.parse(
  await readFile(path.join(root, 'apps/api/openapi/openapi.json'), 'utf8'),
);
const source = await readFile(matrixPath, 'utf8');

const operations = new Set();
for (const [route, item] of Object.entries(openapi.paths)) {
  for (const method of ['get', 'post', 'put', 'patch', 'delete']) {
    if (item[method]) operations.add(`${method.toUpperCase()} ${normalizePath(route)}`);
  }
}

function normalizePath(value) {
  return value
    .split('?')[0]
    .replace(/….*$/, '')
    .replace(/\{[^}]+\}/g, '{}');
}

function targetOperations(target) {
  const found = [];
  for (const code of target.matchAll(/`([^`]+)`/g)) {
    const match = code[1].match(
      /^(GET|POST|PUT|PATCH|DELETE)(?:\/(GET|POST|PUT|PATCH|DELETE))*\s+(\/api\/v1\/\S+)/,
    );
    if (!match) continue;
    const pathValue = normalizePath(match[3].replace(/[;,]$/, ''));
    const methods = code[1].slice(0, code[1].indexOf(' ')).split('/');
    for (const method of methods) found.push(`${method} ${pathValue}`);
  }
  return found;
}

const rows = new Map();
for (const line of source.split('\n')) {
  const cells = line
    .split('|')
    .slice(1, -1)
    .map((cell) => cell.trim());
  if (!/^\d+$/.test(cells[0] || '')) continue;
  const [number, legacy, legacyMethod, purpose, disposition, target, step] = cells;
  rows.set(Number(number), { number, legacy, legacyMethod, purpose, disposition, target, step });
}

if (rows.size !== 159 || Math.max(...rows.keys()) !== 159) {
  throw new Error(`Legacy route inventory drift: expected 159 unique rows, found ${rows.size}`);
}

let executableTargets = 0;
let coveredTargets = 0;
const outputRows = [];
for (const row of [...rows.values()].sort((a, b) => Number(a.number) - Number(b.number))) {
  const targets = ['preserve', 'replace'].includes(row.disposition)
    ? targetOperations(row.target)
    : [];
  executableTargets += targets.length;
  const missing = targets.filter((target) => !operations.has(target));
  coveredTargets += targets.length - missing.length;
  const status =
    targets.length === 0
      ? ['remove', 'frontend-only', 'defer'].includes(row.disposition)
        ? `Accounted: ${row.disposition}`
        : 'Accounted: correction has no executable legacy-equivalent target'
      : missing.length === 0
        ? `Covered (${targets.join('<br>')})`
        : `MISSING (${missing.join('<br>')})`;
  outputRows.push(
    `| ${row.number} | ${row.legacy} | ${row.disposition} | ${row.target.replaceAll('|', '\\|')} | ${status} |`,
  );
}

if (coveredTargets !== executableTargets) {
  const missingRows = outputRows.filter((row) => row.includes('MISSING'));
  throw new Error(
    `OpenAPI does not cover ${executableTargets - coveredTargets} mapped target operations:\n${missingRows.join('\n')}`,
  );
}

const document = `# Step 22 — Endpoint Coverage Matrix

Generated by \`pnpm route-coverage:generate\` from the approved Step 00 parity
matrix and the frozen OpenAPI document. Do not edit this file manually.

## Coverage assertion

- Literal PHP switch routes represented: **154/154**.
- Regex switch routes represented: **2/2**.
- Dynamic pre-switch stock routes represented: **3/3**.
- Total executable legacy route patterns accounted for: **159/159**.
- Mapped executable backend operations present in OpenAPI: **${coveredTargets}/${executableTargets}**.
- Frozen OpenAPI operations in the generated Postman contract catalogue: **${operations.size}/${operations.size}**.

The 154 count is the literal-switch subset, not the complete legacy inventory.
Removed and frontend-only routes are intentionally accounted without inventing a
replacement endpoint. Runtime acceptance evidence is split between the Newman
\`Acceptance\` folder and the complete PostgreSQL/Redis integration suite, as
documented in \`BACKEND-COMPLETION-REPORT.md\`.

| # | Legacy route | Disposition | Approved backend v1 target | Freeze status |
|---:|---|---|---|---|
${outputRows.join('\n')}
`;

await writeFile(outputPath, document);
console.log(`Generated ${path.relative(root, outputPath)} (${rows.size} legacy routes).`);
